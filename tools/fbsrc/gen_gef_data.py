# Characters per string-literal line of a block's text (before C escaping).
_LITERAL_CHUNK = 80
# Most bytes in one DATA block's text: a longer table is split, since a C++ string literal may
# not exceed 65536 characters (clang -Woverlength-strings).
_CHUNK_BYTES = 32768
_FNV_OFFSET = 0xCBF29CE484222325
_FNV_PRIME = 0x100000001B3
_MASK64 = (1 << 64) - 1


@dataclass(frozen=True)
class Variant:
    """One nuclide-data variant: its patch set, its ISOSOURCE and its datachain capture."""

    key: str
    enumerator: str
    patch_set: str
    isosource: str
    capture: str


