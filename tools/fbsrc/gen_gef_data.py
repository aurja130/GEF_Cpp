"""Generate the DATA sources behind ``gef::data::ProgramData`` (M4.2).

Usage (from the repository root)::

    taskset -c 0-9 python3 -m tools.fbsrc.gen_gef_data                 # regenerate
    taskset -c 0-9 python3 -m tools.fbsrc.gen_gef_data --check         # exit 1 when stale
    taskset -c 0-9 python3 -m tools.fbsrc.gen_gef_data --fingerprints  # write the golden

For each of the seven nuclide-data variants (the ``m4-*`` patch sets) the C emitted by fbc is
parsed. Its DATA tables form one chain through their ``label$N`` links; each table holds the
item texts fbc stores, decoded from the C string literals. A table is named after the BASIC
``Restore`` label that points at it: the ``#line`` directive before each ``fb_DataRestore`` call
gives the BASIC file and line. A block identical in every variant is emitted once.

The generated sources go to ``Cpp_implementation/src/data/generated/``; they are formatted with
the repository's ``.clang-format`` (``clang-format`` must be on ``PATH``). ``--fingerprints``
writes ``Cpp_implementation/tests/golden/m4-datachain/fingerprints.txt`` and cross-checks every
item against the reference-store captures.

Exit status: 0 on success, 1 when ``--check`` finds stale generated files, 2 on a failure.
"""

